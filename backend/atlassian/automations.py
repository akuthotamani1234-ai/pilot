"""Validated automation of Jira test cases, kept and reused - so a case that was proven once is not written again by
the AI on every execution (AI answers vary: a case that passed in one run could end 'Not automated' in the next).

  save     after an execution, every requirement test case that PASSED with real checks keeps its executable test:
           the test function and the helpers it calls (from the run's generated_tests), the requirement id,
           acceptance criteria, case version, requirement (source) version, approved scenario (title, steps,
           expected), the selectors it uses, the expected results it checks, the application (origin) and
           environment, and the evidence of the run that proved it (run, execution, checks, time)
  reuse    a later execution - requirement-based or hybrid - hands a compatible automation to the run: the same case
           version, the same requirement version, the same application origin and environment. Anything changed ->
           not compatible -> the AI writes it again
  revalidate  the run first checks the stored code against the CURRENT application (script_generator: validated
           like new AI code, and every selector must be one the run's own exploring saw) and then really runs it.
           A reused test that fails for the TEST's reasons (Requires review / Not automated) is marked stale: the next
           execution regenerates it. One that fails on an application defect stays validated - the test is right and
           the defect is reported (a real bug is never "fixed" by rewriting its test).
Nothing here weakens a check: the stored code is the code that passed, with its QA_EXPECTS_ required results.
"""
from __future__ import annotations

import ast
import json
import re
from datetime import UTC, datetime
from pathlib import Path
from urllib.parse import urlparse

SCHEMA = """
CREATE TABLE IF NOT EXISTS req_automations (
    tenant_id TEXT NOT NULL,
    case_id TEXT NOT NULL,
    status TEXT NOT NULL,
    at TEXT NOT NULL,
    data TEXT NOT NULL,
    PRIMARY KEY (tenant_id, case_id)
);
"""
MAX_CODE = 30000
SELECTOR = re.compile(r"""\.(?:locator|query_selector|wait_for_selector|click|fill)\(\s*(['"])(.+?)\1""")


def connect_schema(db) -> None:
    db.executescript(SCHEMA)


def _now() -> str:
    return datetime.now(UTC).isoformat()


def origin(url: str) -> str:
    u = urlparse(url or "")
    return f"{u.scheme}://{u.netloc}".lower() if u.scheme and u.netloc else ""


def extract(code: str, test: str) -> str:
    """The test function `test` with every top-level helper / constant it uses (transitively) and its QA_EXPECTS_
    line - '' when the function is not in the file."""
    try:
        tree = ast.parse(code)
    except SyntaxError:
        return ""
    lines = code.split("\n")
    nodes = {}
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.ClassDef)):
            nodes[node.name] = node
        elif isinstance(node, ast.Assign):
            for t in node.targets:
                if isinstance(t, ast.Name):
                    nodes[t.id] = node
    if test not in nodes:
        return ""
    want, todo = [], [test, f"QA_EXPECTS_{test}"]
    while todo:
        name = todo.pop()
        node = nodes.get(name)
        if node is None or node in want:
            continue
        want.append(node)
        todo += [n.id for n in ast.walk(node) if isinstance(n, ast.Name) and n.id in nodes]
    imports = [lines[n.lineno - 1] for n in tree.body if isinstance(n, (ast.Import, ast.ImportFrom))]
    parts = []
    for node in sorted(want, key=lambda n: n.lineno):
        start = min([node.lineno] + [d.lineno for d in getattr(node, "decorator_list", [])])
        parts.append("\n".join(lines[start - 1:node.end_lineno]))
    return "\n".join(dict.fromkeys(imports)) + "\n\n\n" + "\n\n\n".join(parts) + "\n"


def save(db, tenant: str, case: dict, run_record: dict, run_dir: Path, target: dict, execution_id: str) -> bool:
    """Keep the automation of a case that PASSED with real checks in this run. Returns True when kept."""
    tests, files = run_record.get("tests") or [], run_record.get("files") or []
    if run_record.get("execution_status") != "Passed" or len(tests) != 1 or len(files) != 1:
        return False
    path = Path(run_dir) / "generated_tests" / str(files[0])
    if path.is_symlink() or not path.is_file() or path.parent.name != "generated_tests":
        return False
    code = extract(re.sub(r"^# generated by: .*\n", "", path.read_text(encoding="utf-8"), count=1), str(tests[0]))
    if not code or len(code) > MAX_CODE:
        return False
    expects = re.findall(r"^QA_EXPECTS_\w+ = (.*)$", code, re.M)
    data = {"case_id": case["id"], "requirement_id": case.get("requirement_id"),
            "criterion_ids": case.get("criterion_ids") or [], "case_version": case.get("version"),
            "source_version": case.get("source_version"),
            "scenario": {k: case.get(k) for k in ("title", "steps", "expected", "preconditions")},
            "test": str(tests[0]), "file": str(files[0]), "code": code,
            # the plan the run designed for it (so a reuse needs no AI to design the case again either)
            "design": {k: run_record.get(k) for k in ("steps", "expected", "pages", "guest", "test_data",
                                                       "preconditions", "assertions", "priority", "type")},
            "selectors": sorted({m[1] for m in SELECTOR.findall(code)})[:60],
            "expected_results": _literal(expects[0]) if expects else [],
            "origin": origin(target.get("url", "")), "environment": target.get("environment") or "test",
            "evidence": {"run": Path(run_dir).name, "execution_id": execution_id, "at": _now(),
                         "checks": run_record.get("check_count"),
                         "screenshots": [str(e) for e in run_record.get("evidence") or []][:5]},
            "reused": 0}
    old = get(db, tenant, case["id"])
    if old and old.get("code") == code:  # (proven again: same code, one more passing run)
        data["reused"] = old.get("reused", 0)
        data["passes"] = old.get("passes", 1) + 1
    else:
        data["passes"] = 1
    with db:
        db.execute("INSERT OR REPLACE INTO req_automations (tenant_id, case_id, status, at, data) VALUES (?,?,?,?,?)",
                   (tenant, case["id"], "validated", _now(), json.dumps(data)))
    return True


def _literal(text: str) -> list:
    try:
        value = ast.literal_eval(text)
    except (ValueError, SyntaxError):
        return []
    return [str(v) for v in value] if isinstance(value, (list, tuple)) else []


def get(db, tenant: str, case_id: str) -> dict | None:
    r = db.execute("SELECT status, data FROM req_automations WHERE tenant_id = ? AND case_id = ?",
                   (tenant, case_id)).fetchone()
    return dict(json.loads(r["data"]), status=r["status"]) if r else None


def compatible(db, tenant: str, case: dict, target: dict) -> dict | None:
    """The validated automation of this case when it still applies: the same case and requirement version, the same
    application and environment. None -> the AI writes the test (again)."""
    a = get(db, tenant, case["id"])
    if not a or a["status"] != "validated":
        return None
    if (a.get("case_version"), a.get("source_version")) != (case.get("version"), case.get("source_version")):
        return None
    if a.get("origin") != origin(target.get("url", "")) or a.get("environment") != (target.get("environment")
                                                                                 or "test"):
        return None
    return a


def mark_stale(db, tenant: str, case_id: str, why: str) -> None:
    a = get(db, tenant, case_id)
    if not a:
        return
    a.update(stale_reason=why[:300], stale_at=_now())
    with db:
        db.execute("UPDATE req_automations SET status = 'stale', at = ?, data = ? WHERE tenant_id = ? AND case_id = ?",
                   (_now(), json.dumps(a), tenant, case_id))


def note_reused(db, tenant: str, case_id: str) -> None:
    a = get(db, tenant, case_id)
    if not a:
        return
    a["reused"] = a.get("reused", 0) + 1
    with db:
        db.execute("UPDATE req_automations SET data = ? WHERE tenant_id = ? AND case_id = ?",
                   (json.dumps(a), tenant, case_id))


def after_execution(db, tenant: str, ex: dict, run_cases: dict[str, dict], results: dict[str, dict],
                    cases: dict[str, dict], run_dir: Path) -> dict:
    """Keep what passed, mark stale what a reused automation failed for test-side reasons. Returns counts."""
    kept = stale = 0
    for cid, res in results.items():
        rec, case = run_cases.get(cid) or {}, cases.get(cid)
        if not case:
            continue
        if res.get("status") == "Passed" and rec:
            kept += save(db, tenant, case, rec, run_dir, ex.get("target") or {}, ex["id"])
        elif rec.get("automation_source") == "reused" and res.get("status") in ("Requires review", "Not automated"):
            mark_stale(db, tenant, cid, f"{res.get('status')}: {res.get('reason') or res.get('actual') or ''}")
            stale += 1
    return {"kept": kept, "stale": stale}
