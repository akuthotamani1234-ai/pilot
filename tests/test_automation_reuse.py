"""Validated automation of Jira cases is kept and reused (backend/atlassian/automations.py,
script_generator.reuse_validated): a case proven once is not re-written by the AI; it is reused only while the case,
the requirement, the application and the environment are the same; it is revalidated against the current run's pages;
a test-side failure of reused code marks it stale (regenerated next time); an application defect does not."""
import json

import pytest

from backend.atlassian import automations, bridge
from tests.test_prerequisites import case

GENERATED = '''# generated by: llm
import re
from playwright.sync_api import expect


def _badge(page):
    return page.locator('[data-test="shopping-cart-badge"]')


def test_ai_flow_2(page):
    page.goto("https://www.saucedemo.com/inventory.html")
    page.locator("#add-to-cart-sauce-labs-backpack").click()
    expect(_badge(page)).to_have_text("1")
    expect(page.locator("body")).to_contain_text("Sauce Labs Backpack")


def test_ai_flow_3(page):
    page.goto("https://www.saucedemo.com/")


QA_EXPECTS_test_ai_flow_2 = ['Sauce Labs Backpack']
'''
CART = case("TC-A-1", "A", "Add a product to the shopping cart", steps=["Add the backpack"],
            expected="the cart shows 'Sauce Labs Backpack'")
TARGET = {"url": "https://www.saucedemo.com/", "environment": "test"}


@pytest.fixture
def db(tmp_path, monkeypatch):
    monkeypatch.setattr(bridge, "refresh", lambda *a, **k: None)
    d = bridge.connect(tmp_path / "req.db")
    bridge._save(d, "t", dict(CART), "test")
    yield d
    d.close()


def _run(tmp_path, status="Passed", **extra):
    run = tmp_path / f"run_{status}"
    (run / "generated_tests").mkdir(parents=True)
    (run / "generated_tests" / "test_flows_ai.py").write_text(GENERATED)
    (run / "test_cases.json").write_text(json.dumps([{
        "requirement_test": "TC-A-1", "execution_status": status, "tests": ["test_ai_flow_2"],
        "files": ["test_flows_ai.py"], "check_count": 2, "evidence": ["screenshots/a.png"], **extra}]))
    return run


def test_only_the_passing_test_and_its_helpers_are_kept_with_its_requirement_context(db, tmp_path):
    ex = bridge.plan(db, "t", ["TC-A-1"], "requirements", TARGET)["execution"]
    bridge.collect(db, "t", ex["id"], _run(tmp_path))
    a = automations.get(db, "t", "TC-A-1")
    assert a["status"] == "validated" and a["requirement_id"] == "A" and a["criterion_ids"] == ["A#AC-1"]
    assert "def test_ai_flow_2" in a["code"] and "def _badge" in a["code"] and "test_ai_flow_3" not in a["code"]
    assert "QA_EXPECTS_test_ai_flow_2" in a["code"] and a["expected_results"] == ["Sauce Labs Backpack"]
    assert '[data-test="shopping-cart-badge"]' in a["selectors"] and a["origin"] == "https://www.saucedemo.com"
    assert a["scenario"]["title"] == CART["title"] and a["evidence"]["run"] == "run_Passed"
    assert (a["case_version"], a["source_version"]) == (1, 1)


@pytest.mark.parametrize("status", ["Failed", "Requires review", "Not run"])
def test_nothing_is_kept_unless_it_passed(db, tmp_path, status):
    ex = bridge.plan(db, "t", ["TC-A-1"], "requirements", TARGET)["execution"]
    bridge.collect(db, "t", ex["id"], _run(tmp_path, {"Requires review": "Failed"}.get(status, status),
                                           failure_category="Test mistake" if status == "Requires review" else ""))
    assert automations.get(db, "t", "TC-A-1") is None


def test_a_later_execution_gets_it_only_while_everything_still_matches(db, tmp_path):
    ex = bridge.plan(db, "t", ["TC-A-1"], "requirements", TARGET)["execution"]
    bridge.collect(db, "t", ex["id"], _run(tmp_path))
    for strategy in ("requirements", "hybrid"):  # (reused by both strategies)
        planned = bridge.plan(db, "t", ["TC-A-1"], strategy, TARGET)
        assert planned["requirement_tests"][0]["automation"]["test"] == "test_ai_flow_2"
        assert planned["execution"]["automation_reuse"] == {"TC-A-1": {"validated_in": "run_Passed", "passes": 1}}
    for other in ({"url": "https://other.example/", "environment": "test"},
                  {"url": "https://www.saucedemo.com/", "environment": "staging"},
                  {"url": "https://www.saucedemo.com/", "environment": "test", "type": "android"}):
        assert "automation" not in bridge.plan(db, "t", ["TC-A-1"], "requirements", other)["requirement_tests"][0]
    changed = dict(bridge.get_case(db, "t", "TC-A-1"), version=2)
    assert automations.compatible(db, "t", changed, TARGET) is None  # (the case was edited: written again)
    newer_story = dict(bridge.get_case(db, "t", "TC-A-1"), source_version=2)
    assert automations.compatible(db, "t", newer_story, TARGET) is None  # (the requirement changed)


def test_reused_code_failing_for_test_reasons_is_stale_but_an_application_defect_keeps_it(db, tmp_path):
    ex = bridge.plan(db, "t", ["TC-A-1"], "requirements", TARGET)["execution"]
    bridge.collect(db, "t", ex["id"], _run(tmp_path))
    ex2 = bridge.plan(db, "t", ["TC-A-1"], "requirements", TARGET)["execution"]
    bridge.collect(db, "t", ex2["id"], _run(tmp_path, "Failed", failure_category="Assertion failure",
                                            automation_source="reused"))
    assert automations.get(db, "t", "TC-A-1")["status"] == "validated"  # (the app broke, the test is right)
    ex3 = bridge.plan(db, "t", ["TC-A-1"], "requirements", TARGET)["execution"]
    run3 = tmp_path / "r3"
    (run3 / "generated_tests").mkdir(parents=True)
    (run3 / "test_cases.json").write_text(json.dumps([{"requirement_test": "TC-A-1", "execution_status": "Failed",
                                                       "failure_category": "Test mistake",
                                                       "automation_source": "reused"}]))
    bridge.collect(db, "t", ex3["id"], run3)
    assert automations.get(db, "t", "TC-A-1")["status"] == "stale"
    assert "automation" not in bridge.plan(db, "t", ["TC-A-1"], "requirements", TARGET)["requirement_tests"][0]


def _pages(selectors):
    return {"inventory_html": {"slug": "inventory_html", "url": "https://www.saucedemo.com/inventory.html",
                               "buttons": [{"selector": s, "text": "x"} for s in selectors], "links": [],
                               "inputs": [], "headings": [], "title": "Swag Labs"}}


def test_the_run_reuses_it_only_after_revalidating_it_against_the_current_pages(monkeypatch):
    from backend import requirement_tests
    from backend.agents import script_generator as sg
    code = automations.extract(GENERATED, "test_ai_flow_2")
    monkeypatch.setenv("QA_REQUIREMENT_TESTS", json.dumps([{
        "id": "rq_tc_a_1", "text": "Add the backpack", "tc": "TC-A-1",
        "automation": {"code": code, "test": "test_ai_flow_2", "validated_in": "run_1"}}]))
    assert requirement_tests.load()[0]["automation"]["test"] == "test_ai_flow_2"
    flow = {"id": "ai_flow_18", "my_test": "rq_tc_a_1", "pages": ["inventory_html"],
            "expected": "the cart shows 'Sauce Labs Backpack'"}
    seen = _pages(["#add-to-cart-sauce-labs-backpack", '[data-test="shopping-cart-badge"]'])
    reused, rest = sg.reuse_validated([flow, {"id": "ai_flow_19", "pages": []}], seen)
    assert list(reused) == ["ai_flow_18"] and [f["id"] for f in rest] == ["ai_flow_19"]
    assert "def test_ai_flow_18(page)" in reused["ai_flow_18"] and "test_ai_flow_2" not in reused["ai_flow_18"]
    assert "QA_EXPECTS_test_ai_flow_18 = ['Sauce Labs Backpack']" in reused["ai_flow_18"]
    gone = _pages(['[data-test="shopping-cart-badge"]'])  # (the add button is not on the page any more)
    reused, rest = sg.reuse_validated([flow], gone)
    assert reused == {} and rest == [flow]  # (no longer fits: the AI writes it again)


def test_the_full_list_with_code_reaches_the_run_through_a_private_file(tmp_path, monkeypatch):
    from backend import requirement_tests
    handoff = tmp_path / ".handoff"
    handoff.mkdir()
    f = handoff / "x.json"
    f.write_text(json.dumps([{"id": "rq_a", "text": "t", "tc": "TC-1",
                              "automation": {"code": "x" * 50000, "test": "test_a"}}]))
    monkeypatch.setenv("QA_REQUIREMENT_TESTS", "[]")
    monkeypatch.setenv("QA_REQUIREMENT_TESTS_FILE", str(f))
    assert len(requirement_tests.load()[0]["automation"]["code"]) == 30000
    monkeypatch.setenv("QA_REQUIREMENT_TESTS_FILE", str(tmp_path / "elsewhere.json"))
    assert requirement_tests.load() == []  # (only the Studio's own hand-off folder)
