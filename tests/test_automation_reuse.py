def test_a_case_with_validated_automation_needs_no_ai_to_be_designed(monkeypatch):
    """With the plan and code that were proven, a Jira case is designed and scripted without asking the AI again -
    a requirement-based execution of proven cases does not vary with the AI (and still runs when it is unavailable)."""
    from backend.agents import test_design
    monkeypatch.setattr(test_design, "llm_enabled", lambda: False)
    monkeypatch.setattr(test_design, "ask_structured", lambda *a, **k: (_ for _ in ()).throw(AssertionError("AI")))
    pages = [{"slug": "inventory_html", "url": "https://www.saucedemo.com/inventory.html", "auth": True,
              "title": "Swag Labs", "headings": [], "buttons": [], "links": [], "inputs": [], "forms": []}]
    design = {"steps": ["Add the backpack", "Open the cart"], "expected": "the cart shows 'Sauce Labs Backpack'",
              "pages": ["inventory_html", "gone_page"], "guest": False, "priority": "high"}
    tests = [{"id": "rq_tc_a_1", "text": "Add the backpack", "tc": "TC-A-1",
              "automation": {"code": "x", "test": "test_ai_flow_2", "validated_in": "run_1", "design": design}},
             {"id": "rq_tc_b_1", "text": "Sort by price", "tc": "TC-B-1"}]
    cases = {c["my_test"]: c for c in test_design.my_test_cases(pages, tests, start=1)}
    proven = cases["rq_tc_a_1"]
    assert proven["kind"] == "flow" and proven["design_source"] == "reused" and proven["pages"] == ["inventory_html"]
    assert proven["steps"] == design["steps"] and proven["tests"] == ["test_ai_flow_1"]
    assert cases["rq_tc_b_1"]["skip_reason"].startswith("Blocked: no AI")  # (the other one still needs an AI)


def test_an_optional_explanation_call_never_stops_the_run_but_a_test_call_does(monkeypatch):
    from backend import llm, runctl
    stops = []
    monkeypatch.setattr(runctl, "request_stop", lambda *a: stops.append(a))
    monkeypatch.setenv("QA_ALLOW_RULES_FALLBACK", "0")
    monkeypatch.setattr(llm, "_ask_once", lambda *a, **k: (_ for _ in ()).throw(llm.LLMError("no credits")))
    monkeypatch.setattr(llm, "llm_enabled", lambda: True, raising=False)
    with llm.optional_ai(), pytest.raises(llm.LLMError):
        llm.ask_llm("names please", agent="test_design", max_attempts=1)
    assert stops == []  # (feature names / failure explanations fall back; the run goes on)
    with pytest.raises(llm.LLMError):
        llm.ask_llm("write the test", agent="script_generator", max_attempts=1)
    assert stops and stops[0][0] == "ai_unavailable"  # (a test-producing call still stops it)


@pytest.mark.parametrize("assertions,expected", [(0, "Requires review"), (3, "Passed")])
def test_worker_assertions_determine_pass_credit(db, tmp_path, assertions, expected):
    ex = bridge.plan(db, "t", ["TC-A-1"], "requirements", TARGET)["execution"]
    run = _run(tmp_path)
    (run / "results.json").write_text(json.dumps([{
        "file": "test_flows_ai.py", "test": "test_ai_flow_2", "outcome": "passed", "checks": assertions}]))
    bridge.collect(db, "t", ex["id"], run)
    row, = bridge.results(db, "t", ex["id"])
    assert row["status"] == expected and row["checks"] == assertions
